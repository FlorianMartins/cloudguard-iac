#!/usr/bin/env python3
"""Keep the security-rules table of the README generated from the registry.

Documentation that is typed by hand drifts; documentation that is generated
cannot. The table between the two markers in ``README.md`` is produced from
:mod:`cloudguard.rules`, and the ``docs`` job of the CI pipeline runs this
script with ``--check`` to refuse any commit where the two disagree.

Usage::

    python scripts/sync_rules_table.py            # rewrite the table
    python scripts/sync_rules_table.py --check    # fail if it is out of date
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
if str(REPO_ROOT) not in sys.path:  # allow running without installing the package
    sys.path.insert(0, str(REPO_ROOT))

from cloudguard.cli import _rules_markdown  # noqa: E402
from cloudguard.rules import all_rules  # noqa: E402

README = REPO_ROOT / "README.md"
BEGIN = "<!-- BEGIN RULES TABLE (generated by scripts/sync_rules_table.py) -->"
END = "<!-- END RULES TABLE -->"


def render_table() -> str:
    """Build the Markdown block, markers included."""
    table = _rules_markdown(all_rules())
    return f"{BEGIN}\n\n{table}\n\n{END}"


def replace_block(content: str, block: str) -> str:
    """Swap the marked block in ``content`` for ``block``."""
    start = content.find(BEGIN)
    end = content.find(END)
    if start == -1 or end == -1:
        raise SystemExit(f"markers not found in {README.name}: expected {BEGIN!r} and {END!r}")
    return content[:start] + block + content[end + len(END) :]


def main() -> int:
    """Rewrite or verify the README table."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit 1 when the README is out of date instead of rewriting it",
    )
    args = parser.parse_args()

    content = README.read_text(encoding="utf-8")
    updated = replace_block(content, render_table())

    if args.check:
        if content != updated:
            print("README.md rules table is out of date — run 'make docs'", file=sys.stderr)
            return 1
        print(f"README.md is in sync ({len(all_rules())} rules)")
        return 0

    if content == updated:
        print(f"README.md already in sync ({len(all_rules())} rules)")
        return 0

    README.write_text(updated, encoding="utf-8")
    print(f"README.md rules table regenerated ({len(all_rules())} rules)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
